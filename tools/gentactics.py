#!/usr/bin/env python3
"""
gentactics.py -- Boss tactics' tables (tactics.asm), and the same tables for
the reference model (tacref.py), so the two cannot disagree.

  lut_TacHits   for a chance h of 0-198, the dice of 256 whose RandAX(0, 200)
                roll, die * 201 / 256, is at or under it (200 is a miss);
                from 199 up it is 255.
  lut_TacQ      the normal tail, P(Z >= z), in 256ths, for z from -4 to 4 in
                sixteenths: 129 words.
  lut_TacL      the normal loss, E[(Z - z)+] = phi(z) - z Q(z), in 256ths,
                the same 129 points.
  lut_TacSleep  a sleeper's turns lost, in 256ths of a round, by max HP 0-80:
                Battle_PlayerTryWakeup wakes one whose max HP is over a roll
                of 0-80 (die * 81 / 256), so 256 / (the dice that wake);
                81 and over always wake, one turn.  Max HP 0 never: 64 rounds.
"""
import math, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DST = os.path.join(ROOT, "gen", "tactics.inc")
CAP = 64 * 256                  # 64 rounds: the most anything is worth


def hits():
    return [sum(1 for b in range(256) if (b * 201) >> 8 <= h and (b * 201) >> 8 != 200) for h in range(199)]


def normal():
    Q, L = [], []
    for j in range(129):
        z = (j - 64) / 16
        q = 0.5 * math.erfc(z / math.sqrt(2))
        phi = math.exp(-z * z / 2) / math.sqrt(2 * math.pi)
        Q.append(int(round(256 * q)))
        L.append(int(round(256 * (phi - z * q))))
    return Q, L


def sleep():
    out = []
    for hp in range(81):
        wake = sum(1 for b in range(256) if (b * 81) >> 8 < hp)
        out.append(CAP if wake == 0 else min(CAP, 65536 // wake))
    return out


def main():
    Q, L = normal()
    o = ["; GENERATED by tools/gentactics.py -- do not edit.", "",
         ";  For a chance 0-198: the dice of 256 whose roll 0-200 is at or under it.",
         "lut_TacHits:"]
    h = hits()
    for i in range(0, 199, 16):
        o.append("  .BYTE " + ", ".join(str(v) for v in h[i:i + 16]))
    o += ["", ";  P(Z >= z) in 256ths, z = -4 to 4 in sixteenths.", "lut_TacQ:"]
    for i in range(0, 129, 16):
        o.append("  .WORD " + ", ".join(str(v) for v in Q[i:i + 16]))
    o += ["", ";  E[(Z - z)+] in 256ths, the same points.", "lut_TacL:"]
    for i in range(0, 129, 16):
        o.append("  .WORD " + ", ".join(str(v) for v in L[i:i + 16]))
    o += ["", ";  A sleeper's turns lost, 256ths of a round, by max HP 0-80.", "lut_TacSleep:"]
    s = sleep()
    for i in range(0, 81, 16):
        o.append("  .WORD " + ", ".join(str(v) for v in s[i:i + 16]))
    open(DST, "w").write("\n".join(o) + "\n")


if __name__ == "__main__":
    main()
