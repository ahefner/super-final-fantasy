#!/usr/bin/env python3
"""genitemmagic.py -- item magic shuffle's two spell pools, from the records.

FFR's ShuffleItemMagic deals spells to every item that casts one, from a pool
its ItemMagicPool names.  Two are ported: All (GetAllSpells: every spell that
does something in battle) and Balanced (GetBalancedSpells: All, less the
strongest and the weakest).  Both are fixed functions of the cartridge's
spell records, so they are worked out here, once, rather than at every cache
build -- and from the cartridge's records, not the option-adjusted ones, so a
world stays a function of the seed and the save.  The rules are randoref's;
tools/test_options.py holds the cart's tables to its own transcription of
FFR's.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import randoref as R

RECORDS = os.path.join(ROOT, "game", "bin", "0C_81E0_magicdata.bin")
OUT = os.path.join(ROOT, "gen", "itemmagic.inc")


def main():
    rec = open(RECORDS, "rb").read()[:64 * 8]
    out = [";  Generated by tools/genitemmagic.py -- do not edit.",
           ";  Item magic's spell pools, spells 0..63 in order.", ""]
    for name, mode in (("All", R.ITEMMAGIC_SHUFFLE), ("Bal", R.ITEMMAGIC_BALANCED)):
        pool = R.itemmagic_pool(rec, mode)
        out.append("IM_%s_N = %d" % (name.upper(), len(pool)))
        out.append("lut_IM%s:" % name)
        for i in range(0, len(pool), 16):
            out.append("  .BYTE " + ", ".join("$%02X" % s for s in pool[i:i + 16]))
        out.append("")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(out))


if __name__ == "__main__":
    main()
