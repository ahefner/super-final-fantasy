#!/usr/bin/env python3
"""genowedits.py -- FFR's overworld map edits as the cart applies them.

Every edit of every list owedits.py transcribes, but CanalSoftLockMountain
(applied by nothing in FFR), sorted by row and, within a row, into FFR's
order of application, so that writing a row's active edits in turn leaves
what FFR's edited map has there.  world.asm's ow_edit walks a row's entries
as each row is decompressed.

    lut_OweRow    257 words: row r's entries are bytes lut_OweRow[r] up to
                  lut_OweRow[r + 1] of lut_OweEnt
    lut_OweEnt    four bytes an entry: its list's gate as a bit of the
                  active-list mask (a word), its x, its tile
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import owedits as O

OUT = os.path.join(ROOT, "gen", "owedits.inc")
ENTRY = 4


def entries():
    """(row, gate, x, tile) in the cart's order."""
    out = []
    for rank, (name, gate) in enumerate(O.ORDER):
        if gate == O.LIST_NONE:
            continue
        for i, (x, y, tile) in enumerate(O.LISTS[name]):
            out.append((y, rank, i, gate, x, tile))
    out.sort()
    return [(y, gate, x, tile) for y, _, _, gate, x, tile in out]


def main():
    ent = entries()
    starts, k = [], 0
    for r in range(257):
        while k < len(ent) and ent[k][0] < r:
            k += 1
        starts.append(k * ENTRY)
    lines = [";  Generated by tools/genowedits.py -- do not edit.",
             ";  FFR's overworld map edits by row (owedits.py).", "",
             "OWE_ENTRIES = %d" % len(ent), "OWE_ENTRY = %d" % ENTRY, "",
             "lut_OweRow:"]
    for i in range(0, 257, 8):
        lines.append("  .WORD " + ", ".join("$%04X" % s for s in starts[i:i + 8]))
    lines.append("lut_OweEnt:")
    for y, gate, x, tile in ent:
        lines.append("  .WORD $%04X\n  .BYTE %3d, $%02X   ; row %d" % (1 << gate, x, tile, y))
    lines.append("")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
