#!/usr/bin/env python3
"""
gencrawl.py -- the credits crawl's perspective, as HDMA tables.

The credits text lies on a mode 7 plane that is tilted back from the screen
about a horizontal line, the way the opening crawl of a certain film is.  With
the matrix's B, C and D held at zero, mode 7 reduces to two numbers per
scanline:

    texture x = A * (screen x - 128) + 128     -- M7A, the horizontal scale
    texture y = M7Y                            -- which row of the text

so the whole effect is an HDMA table for each.  A depends only on the
geometry, so it is computed here and goes into ROM complete.  The row also
moves with the scroll, so what goes into ROM is each line's distance up the
plane, and the credits screen subtracts it from the scroll once a frame into
a buffer the second channel reads.

The geometry, all in screen pixels:

    the eye sits FOCAL pixels in front of the screen, level with EYE_ROW;
    the plane meets the screen along PIVOT_ROW, where text is drawn at ZOOM;
    from there it leans back, away from the eye, by ANGLE degrees.

ANGLE 0 is the plane flat against the screen -- every line at scale 1/ZOOM,
which is the flat scroll this replaced.  At 90 it is a floor.  Lines too far
away to be worth drawing, where a texel is narrower than 1/FAR of a pixel, and
any above the horizon, show nothing.

The text also fades as it recedes: over the top FADE lines of the screen its
colour runs from the background's at line 0 to its own, by a third HDMA table
that rewrites that one CGRAM entry every line.  The colours are the NES's, the
prologue's blue and white, taken from genpal.py so they are the same values
the rest of the port shows.

Each parameter can be overridden from the environment for tuning, without
editing this file:

    CRAWL_ANGLE=60 CRAWL_ZOOM=1.5 ./build.sh
"""
import math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from genpal import NESPAL
DST = os.path.join(os.path.dirname(HERE), "gen", "crawl.inc")


def param(name, default):
    return float(os.environ.get("CRAWL_" + name, default))


ANGLE = param("ANGLE", 50)          # degrees back from the screen
FOCAL = param("FOCAL", 256)         # eye to screen, in pixels
EYE_ROW = param("EYE_ROW", 112)     # the row the eye looks straight at
PIVOT_ROW = param("PIVOT_ROW", 223)  # where the plane meets the screen
ZOOM = param("ZOOM", 1.5)           # magnification of the text at the pivot
FAR = param("FAR", 4.0)             # most texels per pixel worth drawing
FADE = int(param("FADE", 96))       # lines at the top over which the text fades

BACK, INK = 0x01, 0x30              # NES colours: the prologue's blue and white
INK_CGRAM = 1                       # the font's one colour index

LINES = 224
SUBBITS = 3                         # the row is kept in eighths of a texel
CENTRE = 128                        # the text is centred on texel column 128


def geometry():
    """Per screen line: (texels per pixel, texels up the plane) or None."""
    t = math.radians(ANGLE)
    s, c = math.sin(t), math.cos(t)
    yp = EYE_ROW - PIVOT_ROW
    out = []
    for sy in range(LINES):
        y = EYE_ROW - sy                # up from the eye's axis
        denom = FOCAL * c - y * s       # zero at the horizon
        if denom <= 0:
            out.append(None)
            continue
        v = FOCAL * (y - yp) / denom    # pixels up the plane from the pivot
        z = FOCAL + v * s               # depth
        scale = z / FOCAL / ZOOM
        if scale <= 0 or scale > FAR:
            out.append(None)
        else:
            out.append((scale, v / ZOOM))
    return out


def runs(n):
    """HDMA line counts top out at 127."""
    while n > 0:
        k = min(n, 127)
        yield k
        n -= k


def main():
    g = geometry()
    first = next((i for i, e in enumerate(g) if e is not None), None)
    if first is None:
        sys.exit("gencrawl: no line of the plane is visible -- check the angle")
    if any(e is None for e in g[first:]):
        sys.exit("gencrawl: the visible lines are not one run from the bottom")
    lines = LINES - first
    if not 1 <= FADE <= LINES:
        sys.exit("gencrawl: a fade of %d lines does not fit the screen" % FADE)
    a = [round(e[0] * 256) for e in g[first:]]
    v = [round(e[1] * (1 << SUBBITS)) for e in g[first:]]
    if max(a) > 0x7FFF:
        sys.exit("gencrawl: a scale of %.2f is past M7A's range" % (max(a) / 256))
    if not all(-0x4000 < x < 0x4000 for x in v):
        sys.exit("gencrawl: the plane reaches too far for a 16-bit row")

    o = ["; GENERATED by tools/gencrawl.py -- do not edit.",
         "; angle %g, focal %g, eye row %g, pivot row %g, zoom %g, far %g"
         % (ANGLE, FOCAL, EYE_ROW, PIVOT_ROW, ZOOM, FAR),
         "; texels per pixel run from %.3f at the bottom to %.3f at line %d"
         % (a[-1] / 256, a[0] / 256, first),
         "",
         "CRAWL_FIRST   = %d        ; the first line that shows the plane" % first,
         "CRAWL_LINES   = %d        ; ...and how many do" % lines,
         "CRAWL_SUBBITS = %d         ; rows are in 1/%d texel"
         % (SUBBITS, 1 << SUBBITS),
         "CRAWL_VMAX    = %d     ; the top line's distance up the plane, in those"
         % v[0],
         "CRAWL_CENTRE  = %d" % CENTRE,
         ""]

    #  M7A: a direct table, the blank lines first and the plane after.
    o.append("lut_CrawlA:")
    for k in runs(first):
        o.append("  .byte %d" % k)
        o.append("  .word $0100")
    rest = list(a)
    for k in runs(lines):
        o.append("  .byte $80 | %d" % k)
        for i in range(0, k, 8):
            o.append("  .word " + ", ".join("$%04X" % x for x in rest[i:min(i + 8, k)]))
        rest = rest[k:]
    o.append("  .byte 0")
    o.append("")

    #  Each visible line's distance up the plane, top line first.
    o.append("lut_CrawlV:")
    for i in range(0, lines, 8):
        o.append("  .word " + ", ".join("%d" % x for x in v[i:i + 8]))
    o.append("")

    #  M7Y: indirect, so the per-frame buffer can be one contiguous array of
    #  rows with the table's line counts kept out of it.  The blank lines all
    #  point at a single word that lies outside the plane.
    o.append(".macro CRAWL_YTABLE buf, blank")
    for k in runs(first):
        o.append("  .byte %d" % k)
        o.append("  .word .loword(blank)")
    off = 0
    for k in runs(lines):
        o.append("  .byte $80 | %d" % k)
        o.append("  .word .loword(buf) + %d" % (off * 2))
        off += k
    o.append("  .byte 0")
    o.append(".endmacro")

    #  The fade: CGRAM entry INK_CGRAM, a line at a time, in transfer mode 3 --
    #  the index twice to CGADD, then the colour's two bytes to CGDATA.  After
    #  the fade one last write leaves the ink at full strength for the rest of
    #  the frame, and the table ends.
    def snes(nes):
        return [c >> 3 for c in NESPAL[nes]]
    b, k = snes(BACK), snes(INK)
    def mix(t):
        r, g, bl = (round(b[j] + (k[j] - b[j]) * t) for j in range(3))
        return bl << 10 | g << 5 | r
    fade = [mix(i / FADE) for i in range(FADE)]
    o.append("")
    o.append("lut_CrawlFade:")
    rest = list(fade)
    for n in runs(FADE):
        o.append("  .byte $80 | %d" % n)
        for c in rest[:n]:
            o.append("  .byte %d, %d, $%02X, $%02X" % (INK_CGRAM, INK_CGRAM, c & 0xFF, c >> 8))
        rest = rest[n:]
    o.append("  .byte 1")
    o.append("  .byte %d, %d, $%02X, $%02X" % (INK_CGRAM, INK_CGRAM, mix(1) & 0xFF, mix(1) >> 8))
    o.append("  .byte 0")

    os.makedirs(os.path.dirname(DST), exist_ok=True)
    open(DST, "w").write("\n".join(o) + "\n")
    print("crawl: angle %g, lines %d-%d visible, scale %.2f..%.2f, fade %d -> %s"
          % (ANGLE, first, LINES - 1, a[-1] / 256, a[0] / 256, FADE, DST))


if __name__ == "__main__":
    main()
