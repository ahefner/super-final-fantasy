#!/usr/bin/env python3
"""genspellnames.py -- the 64 spell names, as a flat four-bytes-each table.

Why a copy at all.  A chest's description is drawn by DrawDialogueString, whose
"item name" control code ($02) reads lut_ItemNamePtrTbl out of whatever bank is
mapped -- unlike DrawComplexString's, which pages in BANK_ITEMS for itself.  The
dialogue renderer's line breaks map whatever cur_bank names, and that has to be
the options chunk for the RTS to come home, so $02 cannot be used there at all.
Naming the dialogue bank instead reads the table correctly and then crashes on
the way back.

So the chest path expands the name itself.  Following the real pointer table at
runtime would mean a 16-bit index or a direct-page pointer, and the names are not
regularly enough placed to index with eight bits: slot 50's starts at $BEFD and
straddles the page.  A flat table of our own is four bytes times sixty-four, and
slot*4 fits in a byte.

This reads bank $0A through the pointer table rather than assuming the stride, so
it stays correct if the names move.  tools/test_options.py checks the result
against the names the built ROM actually holds, which is the other direction.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

MG_START = 0xB0
SPELLS = 64
PTRTBL = 0xB700                 # lut_ItemNamePtrTbl, in BANK_ITEMS == BANK_DIALOGUE
BANK = os.path.join(ROOT, "game", "bank_0A.dat")
OUT = os.path.join(ROOT, "gen", "spellnames.inc")

#  Every spell name in the cartridge is four characters.  Anything else means
#  the data moved and the four-byte stride below is no longer the right shape.
WIDTH = 4


def main():
    d = open(BANK, "rb").read()

    def at(addr):               # a CPU address in this bank
        return d[addr - 0x8000]

    rows = []
    for slot in range(SPELLS):
        item = MG_START + slot
        p = at(PTRTBL + item * 2) | (at(PTRTBL + item * 2 + 1) << 8)
        name = []
        while len(name) < 16:
            b = at(p + len(name))
            if b in (0x00, 0x01, 0x05):
                break
            name.append(b)
        if len(name) != WIDTH:
            raise SystemExit("genspellnames: spell %d is %d characters, not %d"
                             % (slot, len(name), WIDTH))
        rows.append((slot, name))

    with open(OUT, "w") as f:
        f.write(";  Generated by tools/genspellnames.py -- do not edit.\n")
        f.write(";  The 64 spell names, %d bytes each, so slot*%d indexes them.\n"
                % (WIDTH, WIDTH))
        f.write(";  Read out of game/bank_0A.dat through lut_ItemNamePtrTbl.\n\n")
        f.write("lut_SpellNames:\n")
        for slot, name in rows:
            f.write("  .BYTE %s\n" % ", ".join("$%02X" % b for b in name))
        f.write("lut_SpellNamesEnd:\n")
        f.write('.assert lut_SpellNamesEnd - lut_SpellNames = %d, error, '
                '"spell name table is the wrong size"\n' % (SPELLS * WIDTH,))
    print("spell names: %d x %d -> gen/spellnames.inc" % (SPELLS, WIDTH))


if __name__ == "__main__":
    main()
