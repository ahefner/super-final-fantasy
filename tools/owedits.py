"""owedits.py -- FFR's overworld map edits, transcribed.

Every list in FFR's OverworldMapEdits.cs and OverworldCardiaLandBridge.cs
(FF1Lib), each as its (x, y, tile) writes in FFR's order, comments dropped.
FFR applies a list by writing its tiles into the decompressed map in that
order (OverworldMap.ApplyMapEdits), and the lists in the order its
constructor adds them, which is ORDER's below; only the Cardia group's lists
ever write one tile twice.  CanalSoftLockMountain is defined there and
applied by nothing, so it is here for completeness and gated by no setting.

The cart applies them as each row is decompressed (src/world.asm's
ow_editrow, from gen/owedits.inc by tools/genowedits.py).
tools/test_options.py holds this file to FFR's source when the source is
beside the tree.
"""

#  The edit settings, a bit each in RANDO_OWEDITS (snesmap.inc's OWEDIT_*),
#  as FFR's Flags.cs names them, and as its overworld tab labels them.
SETTINGS = [
    "MapOpenProgression",          # 0  Early Open Progression
    "MapOpenProgressionExtended",  # 1  Extended Open Progression
    "MapOpenProgressionDocks",     # 2  Northern Docks
    "MapAirshipDock",              # 3  Ryukahn Desert Dock
    "MapBahamutCardiaDock",        # 4  Bahamut Cardia Dock
    "MapLefeinRiver",              # 5  Lefein River Dock
    "MapBridgeLefein",             # 6  Bridge to Lefein
    "MapGaiaMountainPass",         # 7  Gaia Mountain Pass
    "MapHighwayToOrdeals",         # 8  Highway to Ordeals
    "MapRiverToMelmond",           # 9  River to Melmond
    "MapSardasForest",             # 10 Sarda's Forest
    "MapAirshipHike",              # 11 Hiking Trail to Airship
    "MapCardiaLandBridge",         # 12 Cardia Land Bridge
    "ShipDrydock",                 # 13 Ship in Drydock (FFR's treasure tab)
]
BRIDGE_LEFEIN = 6
SARDAS_FOREST = 10
CARDIA_BRIDGE = 12
SHIP_DRYDOCK = 13

#  Each list's gate: its bit in the active-list mask (active_lists; the
#  cart's ow_lists).  A setting's own bit, but for FFR's two Cardia rules:
#  BahamutCardiaDock applies only without the land bridge, and
#  CardiaLandBridgeBahamutDock only with both.  LIST_NONE: never applied.
BAHAMUT_DOCK = 4
LIST_BAHAMUT_BRIDGE = 14
LIST_NONE = 15

ORDER = [  # FFR's application order, and each list's gate
    ("VolcanoIceRiver", 0),
    ("ConeriaToDwarves", 0),
    ("DwarvesNorthwestGrass", 1),
    ("OnracDock", 2),
    ("MirageDock", 2),
    ("AirshipDock", 3),
    ("BahamutCardiaDock", BAHAMUT_DOCK),
    ("LefeinRiverDock", 5),
    ("BridgeToLefein", BRIDGE_LEFEIN),
    ("GaiaMountainPass", 7),
    ("HighwayToOrdeals", 8),
    ("RiverToMelmond", 9),
    ("SardasForest", SARDAS_FOREST),
    ("AirshipHike", 11),
    ("CardiaLandBridge", CARDIA_BRIDGE),
    ("CardiaLandBridgeBahamutDock", LIST_BAHAMUT_BRIDGE),
    ("GaiaDrydock", SHIP_DRYDOCK),
    ("CanalSoftLockMountain", LIST_NONE),
]

#  FFR's other effects of the settings, the ones this port carries: Bridge
#  to Lefein moves the BRIDGE there (Overworld.cs) and, since its edits
#  delete Matoya's dock, moors a ship that would have berthed there at
#  Coneria's instead (ShipLocations.UpdateDocks); Ship in Drydock moors
#  every ship at Gaia's drydock (Dock.GaiaDrydock, the same routine).
BRIDGE_LEFEIN_XY = (230, 123)
DRYDOCK_XY = (211, 31)


def list_cubes(gate):
    """When a list with this gate applies, as worldgraph's conditions have
    it: cubes (on, off) of RANDO_OWEDITS bits, the settings with every bit
    of `on` and none of `off` -- active_lists's two Cardia rules spelled
    out."""
    if gate == LIST_NONE:
        return []
    if gate == LIST_BAHAMUT_BRIDGE:
        return [(1 << BAHAMUT_DOCK | 1 << CARDIA_BRIDGE, 0)]
    if gate == BAHAMUT_DOCK:
        return [(1 << BAHAMUT_DOCK, 1 << CARDIA_BRIDGE)]
    return [(1 << gate, 0)]


def graph_edits():
    """Every list in FFR's order with when it applies: what worldgraph's
    edited overworld is built from."""
    return [(list_cubes(gate), LISTS[name]) for name, gate in ORDER]


def graph_positions(vanilla):
    """worldgraph's positions (romdata.VANILLA_POS) as the settings move
    them, each a list of (cube, (x, y)): the BRIDGE under Bridge to Lefein,
    the ship under Ship in Drydock."""
    pos = {k: [((0, 0), xy)] for k, xy in vanilla.items()}
    bl, dd = 1 << BRIDGE_LEFEIN, 1 << SHIP_DRYDOCK
    pos["bridge"] = [((0, bl), vanilla["bridge"]), ((bl, 0), BRIDGE_LEFEIN_XY)]
    pos["ship"] = [((0, dd), vanilla["ship"]), ((dd, 0), DRYDOCK_XY)]
    return pos


def positions(vanilla, settings):
    """The same, for one combination of settings: plain (x, y)."""
    return {k: [xy for (on, off), xy in v if settings & on == on and not settings & off][0]
            for k, v in graph_positions(vanilla).items()}


def active_lists(settings):
    """The active-list mask for RANDO_OWEDITS bits `settings`."""
    m = settings & ((1 << len(SETTINGS)) - 1)
    if m >> CARDIA_BRIDGE & 1:
        if m >> BAHAMUT_DOCK & 1:
            m |= 1 << LIST_BAHAMUT_BRIDGE
        m &= ~(1 << BAHAMUT_DOCK)
    return m


def apply(tiles, settings):
    """A copy of `tiles`, the 65,536 overworld tiles row-major, with the
    edits `settings` turns on written in, in FFR's order."""
    t = list(tiles)
    m = active_lists(settings)
    for name, gate in ORDER:
        if m >> gate & 1:
            for x, y, tile in LISTS[name]:
                t[x | y << 8] = tile
    return t


