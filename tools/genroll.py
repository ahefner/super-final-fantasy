#!/usr/bin/env python3
"""
genroll.py -- the pictures New Game's roll screen can show (roll.asm).

While New Game rolls the seed, the screen shows one of the game's own map
sprites scaled up eight times -- every pixel a character cell -- walking in
place, the seed choosing which (user, 2026-10-14).  The choices are every
map object graphic some map uses, but the three that are not creatures (a
pole, the black orb, the rod plate) and Bahamut -- no black outline, so brown
on the blue clashes, and no step (user, 2026-10-15) -- and the twelve
classes' mapmen.

Each has an effect, lut_RollFx: most walk in place, the two frames swapping;
a sprite whose leg tiles are mirror images has no second frame to show, so
it hops instead, half a cell on the same beat -- the Vampire on black
(user, 2026-10-15: he throbbed red before) -- but the sleeping Elf Prince,
who cannot be hopping about like a grasshopper, sleeps while the backdrop
breathes slowly from black to a dim blue (user).  A throb's byte is the
fixed colour's channels (COLDATA's bits 7-5) with FX_THROB, and FX_SLOW for
half the speed and half the brightness; FX_BLACK puts any on black.

For each, the four tiles of its facing-down pose (tiles 0-3 of its sixteen,
as lut_2x2MapObj_Down and lut_PlayerMapmanSprTbl draw it) in NES 2bpp, and
its six colours in SNES form: the top half's three, then the legs' three.
An object's colours are sprite palettes 2 and 3 of the first map it stands
on; a mapman's are palettes 0 and 1 of the overworld's, with each half's
second colour its class's (lut_MapmanPalettes), as LoadSMPalettes sets them.

Read from the game's own banks (game/bank_00.dat, bank_02.dat); the NES
colours in SNES form from nescol.inc, which genpal.py writes first.
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DST = os.path.join(ROOT, "gen", "roll.inc")

#  Where things are, as Constants.inc has them: bank $00 and $02 at $8000.
MAPOBJGFX = 0xAE00 - 0x8000     # object id -> graphic id, $D0 of them
MAPOBJECTS = 0xB400 - 0x8000    # per map, $30 bytes: 15 objects of id, x, y
SMPALETTES = 0xA000 - 0x8000    # per map, $30 bytes: sprite palettes at +$10
MAPMANPAL = 0x83A0 - 0x8000     # per class, the two halves' second colours
MAPOBJCHR = 0xA200 - 0x8000     # in bank $02: per graphic, sixteen tiles
MAPMANCHR = 0x9000 - 0x8000     # in bank $02: per class, sixteen tiles
MAPS = 61
CLASSES = 12
LEFT_OUT = {0x11, 0x12, 0x1B,  # a pole, the black orb, the rod plate
            0x17}              # Bahamut
FX_WALK, FX_HOP, FX_THROB, FX_SLOW, FX_BLACK = 0, 1, 2, 1, 0x10   # FX_SLOW only with FX_THROB
BLUE = 0x80
SPECIAL = {0x1D: FX_HOP | FX_BLACK,              # the Vampire
           0x1A: BLUE | FX_THROB | FX_SLOW}      # the Elf Prince, asleep


def mirrored(chr64):
    """Tile 3 the mirror image of tile 2: the walking frame, which swaps and
    mirrors the legs, is then the standing one."""
    m = lambda b: int("{:08b}".format(b)[::-1], 2)
    return all(m(chr64[48 + i]) == chr64[32 + i] for i in range(16))


def choices():
    b0 = open(os.path.join(ROOT, "game", "bank_00.dat"), "rb").read()
    b2 = open(os.path.join(ROOT, "game", "bank_02.dat"), "rb").read()
    col = {int(m.group(1), 16): int(m.group(2), 16) for m in re.finditer(
        r"NESCOL_([0-9A-F]{2}) = \$([0-9A-F]{4})", open(os.path.join(ROOT, "src", "nescol.inc")).read())}
    first = {}
    for m in range(MAPS):
        for o in range(15):
            oid = b0[MAPOBJECTS + m * 0x30 + o * 3]
            if oid:
                first.setdefault(b0[MAPOBJGFX + oid], m)
    pal = lambda m: b0[SMPALETTES + m * 0x30:SMPALETTES + m * 0x30 + 0x30]
    out = []
    for g in sorted(first):
        if g in LEFT_OUT:
            continue
        p = pal(first[g])
        chr64 = b2[MAPOBJCHR + g * 0x100:][:64]
        fx = SPECIAL.get(g, FX_HOP if mirrored(chr64) else FX_WALK)
        out.append(("graphic $%02X (map %d)" % (g, first[g]), chr64,
                    [col[p[0x18 + i] & 0x3F] for i in (1, 2, 3)] + [col[p[0x1C + i] & 0x3F] for i in (1, 2, 3)], fx))
    ow = pal(0)
    for c in range(CLASSES):
        top, bot = list(ow[0x10:0x14]), list(ow[0x14:0x18])
        top[2], bot[2] = b0[MAPMANPAL + c * 2], b0[MAPMANPAL + c * 2 + 1]
        chr64 = b2[MAPMANCHR + c * 0x100:][:64]
        out.append(("class %d" % c, chr64,
                    [col[top[i] & 0x3F] for i in (1, 2, 3)] + [col[bot[i] & 0x3F] for i in (1, 2, 3)],
                    FX_HOP if mirrored(chr64) else FX_WALK))
    return out


def main():
    cs = choices()
    o = ["; GENERATED by tools/genroll.py -- do not edit.",
         "; The roll screen's pictures: %d map sprites, the seed picks one." % len(cs),
         "", "ROLL_SPRITES = %d" % len(cs), "",
         ";  Each: tiles 0-3 of its sixteen, its facing-down pose, NES 2bpp.",
         "lut_RollChr:"]
    for name, chr64, _, _ in cs:
        o.append("  ; " + name)
        for t in range(4):
            o.append("  .byte " + ", ".join("$%02X" % b for b in chr64[t * 16:t * 16 + 16]))
    o += ["", ";  Each: the top half's colours 1-3, then the legs', SNES BGR.", "lut_RollPal:"]
    for name, _, c, _ in cs:
        o.append("  .word " + ", ".join("$%04X" % v for v in c) + "   ; " + name)
    o += ["", ";  Each: 0 walks, 1 hops (no second frame), or 2 the backdrop throbs:",
          ";  COLDATA's channels with it, and 1 for slow; $10 a black backdrop.", "lut_RollFx:"]
    for name, _, _, fx in cs:
        o.append("  .byte $%02X   ; %s" % (fx, name))
    open(DST, "w").write("\n".join(o) + "\n")


if __name__ == "__main__":
    main()
