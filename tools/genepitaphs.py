#!/usr/bin/env python3
"""genepitaphs.py -- the epitaphs on Elfland's four gravestones.

FFR (Dialogues.cs, TombstoneDialogue) puts one of four epitaphs for members of
its community on Elfland's gravestone, dialogue $DB.  Here all four stand, one
on each stone, left to right in the order FFR lists them (user, 2026-11-17:
"left to right"), whatever the options (user, 2026-11-16: "not a flag, an
unconditional tribute").  Elfland's graveyard has three stones in the game;
mkrom adds a fourth at the right-hand end (overlay_elfgrave).

The words are FFR's, spaced as FFR spaces them -- centred on 24 columns --
except Monoci85's, which the user rewrote to fit (2026-11-17), its first line
centred over its second.

rando_dlgtext (dlgtext.inc) copies the one the party faces into OPTDESC, so
each is coded with the game's letter pairs, as the game's lines are: Disch's
runs to 99 characters and OPTDESC holds 80 bytes.  Written to gen/epitaphs.inc.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import genmaps as GM                      # noqa: E402 -- the font and the pairs

OUT = os.path.join(ROOT, "gen", "epitaphs.inc")

#  Left to right: stones at x = GRAVE_X0 .. GRAVE_X0 + 3 of row GRAVE_ROW.
GRAVE_X0, GRAVE_ROW = 33, 10
EPITAPHS = [
    ("Disch", "  You stand now on the\n  shoulders of Disch,\n       a titan of\n"
              "     Final Fantasy\n      development"),
    ("Monoci85", "   Here lies Monoci85.\nSage, Mentor, and Friend."),
    ("HaateXIII", "     For HaateXIII,\n    Your Voice Will\n       be Missed\n      Car-Bo-Nate"),
    ("tetron", "     tetron, friend.\n     your impact was\n      immeasurable"),
]

#  The dialogue box: a line holds 25 characters (test_rando_dialogue's
#  BOX_COLS), and six lines fit.
BOX_COLS, BOX_LINES = 25, 6
DLG_NL = 0x01


def code(text):
    """The text in the game's encoding, its letter pairs taken wherever they
    save a byte (fewest bytes overall), and the terminator."""
    d1, d2 = GM.dte()
    pairs = {(a, b): GM.DTE_FIRST + i for i, (a, b) in enumerate(zip(d1, d2))}
    raw = [DLG_NL if c == "\n" else GM.FONT[c] for c in text]
    n = len(raw)
    cost, take = [0] * (n + 1), [1] * (n + 1)
    for i in range(n - 1, -1, -1):
        cost[i], take[i] = cost[i + 1] + 1, 1
        if i + 1 < n and (raw[i], raw[i + 1]) in pairs and cost[i + 2] + 1 < cost[i]:
            cost[i], take[i] = cost[i + 2] + 1, 2
    out, i = [], 0
    while i < n:
        out.append(pairs[(raw[i], raw[i + 1])] if take[i] == 2 else raw[i])
        i += take[i]
    return bytes(out + [0])


def main():
    o = [";  Generated by tools/genepitaphs.py -- do not edit.  The epitaphs on",
         ";  Elfland's gravestones, left to right, coded with the game's pairs",
         ";  (rando_dlgtext, dlgtext.inc).",
         "",
         "GRAVE_X0      = %d" % GRAVE_X0,
         "GRAVE_ROW     = %d" % GRAVE_ROW,
         "GRAVE_N       = %d" % len(EPITAPHS)]
    for k, (name, text) in enumerate(EPITAPHS):
        rows = text.split("\n")
        if len(rows) > BOX_LINES or max(map(len, rows)) > BOX_COLS:
            sys.exit("genepitaphs: %s's epitaph is wider or taller than the box" % name)
        b = code(text)
        if len(b) > GM.DLG_MAX:
            sys.exit("genepitaphs: %s's epitaph is %d bytes, past OPTDESC's %d" % (name, len(b), GM.DLG_MAX))
        o.append("lut_Epitaph%d:   ; %s: \"%s\"" % (k, name, " / ".join(r.strip() for r in rows)))
        for i in range(0, len(b), 16):
            o.append("  .BYTE " + ", ".join("$%02X" % v for v in b[i:i + 16]))
    o.append("lut_EpitaphLo:")
    o.append("  .BYTE " + ", ".join("<lut_Epitaph%d" % k for k in range(len(EPITAPHS))))
    o.append("lut_EpitaphHi:")
    o.append("  .BYTE " + ", ".join(">lut_Epitaph%d" % k for k in range(len(EPITAPHS))))
    with open(OUT, "w") as f:
        f.write("\n".join(o) + "\n")


if __name__ == "__main__":
    main()
